"""Regenerate src/import_names.inc (NID#library -> symbol name) from a game's real imports.

runtime_lookup() binds the runtime's name tables through this list, so a function the runtime
implements is only reachable when its NID is listed here. Names come from shadPS4's aerolib
(src/core/aerolib/aerolib.inl), which this repository does not vendor.

Usage: python scripts/gen_import_names.py <game dir> --aerolib <aerolib.inl>   (or OSL_AEROLIB)
"""
import argparse
import os
from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import game_profiles  # noqa: E402
from ps4_module import read_module  # noqa: E402

INC = Path(__file__).resolve().parent.parent / 'src' / 'import_names.inc'
# Imports aerolib does not name; the names follow medievil_pc's table (sceDiscMap_<hash>).
EXTRA_NAMES = {'ioKMruft1ek': 'sceDiscMap_8A828CAEE7EDD5E9'}
HEADER = ('/* NID -> symbol name for the eboot and bundled-module imports (diagnostics and runtime lookup).\n'
          ' * Generated by scripts/gen_import_names.py; names from shadPS4 aerolib. */\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('game', type=Path)
    parser.add_argument('--aerolib', type=Path, default=os.environ.get('OSL_AEROLIB'))
    args = parser.parse_args()
    if not args.aerolib or not Path(args.aerolib).is_file():
        parser.error('aerolib.inl not found: pass --aerolib or set OSL_AEROLIB')
    profile = game_profiles.profile(args.game)
    modules = list(profile['modules']) if profile else ['libc.prx']
    extra = list(profile['extra_executables']) if profile else []
    names = dict(re.findall(r'STUB\(\s*"([^"]+)"\s*,\s*([^)\s]+)\s*\)', Path(args.aerolib).read_text(errors='replace')))
    names.update(EXTRA_NAMES)
    paths = [args.game / 'eboot.bin'] + [args.game / 'sce_module' / m for m in modules] + [args.game / e for e in extra]
    found = {}
    for path in paths:
        for s in read_module(path)['symbols']:
            if s['section'] or not s['identity']:
                continue
            nid, lib = s['identity'][0], s['identity'][1][0]
            if lib == 'libScePosix':
                lib = 'libkernel'  # runtime.c canonical_name()
            if nid in names:
                found[f'{nid}#{lib}'] = names[nid]
    INC.write_text(HEADER + ''.join(f'{{"{k}","{v}"}},\n' for k, v in sorted(found.items())), newline='\n')
    print(f'{len(found)} names written to {INC}')


if __name__ == '__main__':
    main()
